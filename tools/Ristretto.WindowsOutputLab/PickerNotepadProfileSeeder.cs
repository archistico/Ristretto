using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using TextExpander.Core;
using TextExpander.Infrastructure.Storage;

namespace Ristretto.WindowsOutputLab;

/// <summary>
/// Creates one isolated, non-overwriting SQLite library for a previously prepared
/// synthetic Notepad acceptance session. Uses the production store and model,
/// never the user's default profile. No input is sent to any editor.
/// </summary>
internal static class PickerNotepadProfileSeeder
{
    internal const string Trigger = ";ristretto-test";
    private const string SessionSchema = "ristretto/notepad-qualification-session/1";

    internal static async Task<string> SeedAsync(string projectRoot, string token)
    {
        if (token.Length != 32 || token.Any(c => !Uri.IsHexDigit(c) || char.IsUpper(c)))
            throw new ArgumentException("Invalid synthetic session token.", nameof(token));
        var root = Path.GetFullPath(projectRoot);
        if (!File.Exists(Path.Combine(root, "Ristretto.sln")))
            throw new InvalidOperationException("Not a Ristretto source root.");

        var container = Path.Combine(root, ".local-cache", "notepad-qualification");
        var session = Path.Combine(container, token);
        var metadataPath = Path.Combine(session, "session.json");
        var documentPath = Path.Combine(session, "notepad-synthetic.txt");
        var fixturePath = Path.Combine(root, "data", "PICKER_INSERT_SYNTHETIC_FIXTURE.txt");
        var profile = Path.Combine(session, "profile");

        // Reject symlink/junction traversal on every session-storage component.
        foreach (var folder in new[] { Path.Combine(root, ".local-cache"), container, session })
            if (!Directory.Exists(folder) || new DirectoryInfo(folder).LinkTarget is not null)
                throw new InvalidOperationException("Synthetic session directory missing or linked.");
        foreach (var file in new[] { metadataPath, documentPath, fixturePath })
            if (!File.Exists(file) || new FileInfo(file).LinkTarget is not null)
                throw new InvalidOperationException("Synthetic session input missing or linked.");
        if (Directory.Exists(profile) || File.Exists(profile))
            throw new InvalidOperationException("Synthetic profile already exists; refusing to overwrite.");

        var fixtureBytes = await File.ReadAllBytesAsync(fixturePath).ConfigureAwait(false);
        var fixture = new UTF8Encoding(false, true).GetString(fixtureBytes).TrimStart('\uFEFF');
        if (fixture.Length == 0 || fixture.Contains('\0'))
            throw new InvalidOperationException("Synthetic fixture is empty or invalid.");
        var metadataBytes = await File.ReadAllBytesAsync(metadataPath).ConfigureAwait(false);
        using var metadata = JsonDocument.Parse(metadataBytes);
        var info = metadata.RootElement;
        string Field(string key) => info.GetProperty(key).GetString() ?? "";
        var version = (await File.ReadAllTextAsync(Path.Combine(root, "VERSION.txt")).ConfigureAwait(false)).Trim();
        if (Field("schema") != SessionSchema || Field("session") != token ||
            Field("version") != version || Field("document_name") != "notepad-synthetic.txt" ||
            Field("fixture_sha256") != Digest(Encoding.UTF8.GetBytes(fixture)) ||
            Field("baseline_sha256") != Digest(await File.ReadAllBytesAsync(documentPath).ConfigureAwait(false)))
            throw new InvalidOperationException("Synthetic session metadata or baseline changed.");

        // The session path is unique and freshly generated by qualify_notepad.py.
        // Never accept an existing destination, including an empty one.
        Directory.CreateDirectory(profile);
        var store = new SqliteLibraryStore(Path.Combine(profile, "library.db"));
        await store.InitializeAsync().ConfigureAwait(false);
        var group = await store.CreateGroupAsync("Prova Notepad sintetica").ConfigureAwait(false);
        await store.SaveSnippetAsync(new SnippetDraft(null, group.Id,
            "Test Unicode multilinea", Trigger, fixture, "Solo test: nessun dato personale", true, null))
            .ConfigureAwait(false);
        var readback = await store.ReadAsync().ConfigureAwait(false);
        if (readback.Groups.Count != 1 || readback.Snippets.Count != 1 ||
            readback.Snippets[0].Trigger != Trigger || readback.Snippets[0].Content != fixture)
            throw new InvalidOperationException("Profile readback does not match synthetic fixture.");
        return profile;
    }

    private static string Digest(byte[] value) => Convert.ToHexString(SHA256.HashData(value)).ToLowerInvariant();
}
